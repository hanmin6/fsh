"""Run against the local Vite preview; all mutations use synthetic demo data.
Usage: python3 tests/unified_ui_browser.py (requires Python Playwright and Chrome).
"""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
BASE='http://127.0.0.1:5176/preview.html?preview=1'
OUT=ROOT/'test-results'/'unified-ui'
OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.getenv('BROWSER_EXECUTABLE') or ('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' if Path('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome').exists() else None),headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.route('**/client/custom/res/fusanhe/logo-full.png',lambda r:r.fulfill(path=str(ROOT/'client/custom/res/fusanhe/logo-full.png'),content_type='image/png'))
    page.goto(BASE)
    expect(page.get_by_text('抓取正常',exact=True)).to_have_count(2)
    page.screenshot(path=str(OUT/'home-desktop.png'))
    # A failed worker leaves the other platform green, expands red and retains success time.
    # Force initial database persistence by reading a conversation (mark unread).
    page.get_by_role('button',name='消息中心',exact=True).first.click()
    page.get_by_text('样品已收到，口感很好。请提供正式报价。',exact=True).click()
    inspector=page.locator('.w-chat-inspector')
    expect(inspector.get_by_text('AI 回复与审核',exact=True)).to_be_visible()
    inspector.get_by_role('button',name='批准并创建发送任务',exact=True).click()
    dialog=page.get_by_role('dialog')
    expect(dialog.get_by_role('button',name='确认批准',exact=True)).to_be_disabled()
    dialog.get_by_role('checkbox').check()
    dialog.get_by_role('button',name='确认批准',exact=True).click()
    expect(inspector.get_by_text('示例已批准任务',exact=True)).to_be_visible()
    expect(inspector.get_by_role('textbox',name='回复草稿',exact=True)).to_have_attribute('readonly','')
    inspector.get_by_role('button',name='人工接管',exact=True).click()
    page.get_by_role('dialog').get_by_role('button',name='确认切换').click()
    expect(inspector.get_by_role('button',name='恢复 AI 辅助')).to_be_visible()
    inspector.get_by_role('button',name='创建交接任务').click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_role('textbox',name='需求摘要').fill('确认包装后跟进报价')
    dialog.get_by_role('button',name='创建交接任务').click()
    expect(inspector.get_by_text('确认包装后跟进报价',exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'message-desktop.png'))
    page.evaluate("""()=>{const db=JSON.parse(sessionStorage.getItem('fsh-ui-demo-v2'));db.AutomationAgent[1].status='loginExpired';sessionStorage.setItem('fsh-ui-demo-v2',JSON.stringify(db))}""")
    page.goto(BASE)
    expect(page.locator('.w-capture.error.expanded')).to_have_count(1)
    expect(page.locator('.w-capture.healthy')).to_have_count(1)
    expect(page.get_by_text('登录已失效，新消息暂未更新。',exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'home-error.png'))
    page.get_by_role('button',name='收起异常详情').click()
    expect(page.locator('.w-capture.error.expanded')).to_have_count(0)
    page.get_by_role('button',name='展开异常详情').click()
    page.evaluate("""()=>{const db=JSON.parse(sessionStorage.getItem('fsh-ui-demo-v2'));db.AutomationAgent[1].status='online';sessionStorage.setItem('fsh-ui-demo-v2',JSON.stringify(db))}""")
    page.reload()
    expect(page.get_by_text('抓取正常',exact=True)).to_have_count(2)
    page.get_by_role('button',name='客户与评级',exact=True).click()
    page.get_by_text('North Harbor Foods',exact=True).first.click()
    page.get_by_role('button',name='调整',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_role('textbox',name='调整依据').fill('采购需求及包装已人工核对')
    dialog.get_by_role('combobox',name='人工评级').select_option('S')
    dialog.get_by_role('button',name='保存人工评级').click()
    expect(page.get_by_text('采购需求及包装已人工核对',exact=True)).to_be_visible()
    page.get_by_role('button',name='知识库',exact=True).click()
    for tab in ['商品与规格','证书与报告','知识文档','素材']:
        page.locator('.w-page-tabs').get_by_role('button',name=tab,exact=True).click()
        expect(page.locator('.w-page-tabs').get_by_role('button',name=tab)).to_have_attribute('aria-pressed','true')
    page.get_by_role('button',name='AI 工作中心',exact=True).click()
    for tab in ['创作任务','我的作品','开始创作']:
        page.locator('.w-page-tabs').get_by_role('button',name=tab,exact=True).click()
    page.goto(BASE+'&workspace=messages&record=v2')
    page.set_viewport_size({'width':390,'height':844})
    expect(page.locator('.w-chat')).to_be_visible()
    page.screenshot(path=str(OUT/'message-mobile.png'))
    chat=page.locator('.w-chat').bounding_box()
    assert chat and chat['width']>330, chat
    assert not page.evaluate('document.querySelector(".w-main").scrollWidth > document.querySelector(".w-main").clientWidth')
    page.get_by_role('button',name='客户资料',exact=True).click()
    expect(page.locator('.w-chat-inspector')).to_be_visible()
    page.goto(BASE)
    page.screenshot(path=str(OUT/'home-mobile.png'))
    assert not errors, errors
    # Exercise recovery and failed rechecks without remounting the component.
    page.goto('http://127.0.0.1:5176/tests/capture.html')
    expect(page.get_by_text('抓取正常',exact=True)).to_have_count(2)
    page.locator('#fail').click()
    page.get_by_role('button',name='重新检查平台状态').click()
    expect(page.locator('.w-capture.error.expanded')).to_have_count(1)
    expect(page.get_by_text('异常发现：',exact=False)).not_to_contain_text('未记录')
    page.get_by_role('button',name='收起异常详情').click()
    page.locator('#recover').click()
    page.get_by_role('button',name='重新检查平台状态').click()
    expect(page.get_by_text('已恢复正常',exact=True)).to_be_visible()
    expect(page.locator('.w-capture.error')).to_have_count(0)
    page.locator('#fail').click()
    page.get_by_role('button',name='重新检查平台状态').click()
    expect(page.locator('.w-capture.error.expanded')).to_have_count(1)
    page.locator('#transport').click()
    page.get_by_role('button',name='重新检查平台状态').click()
    expect(page.get_by_role('alert')).to_contain_text('状态检查失败')
    expect(page.locator('.w-capture.error.expanded')).to_have_count(1)
    browser.close()
print('PASS: capture independence, errors, collapse, recovery, approval gating, takeover, handoff, ratings, tabs and mobile layout')
